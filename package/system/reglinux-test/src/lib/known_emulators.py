# Discover emulator binary names from the generated rs_systems.cfg.
# Used by no_orphan_emulator probe — replaces hard-coded pattern list.
#
# rs_systems.cfg is es-system's build-time output and the POST-gating artifact:
# it lists only the emulators/cores actually built for this board, which is
# exactly what an orphan-process probe wants (es_systems.yml is the full
# availability matrix including things this image never shipped). It is also
# the only systems source installed on target — the es_systems.yml /
# launcher-defaults.yml pair this used to read are build-time inputs.
#
# Schema returned by load():
#   {system_name: {"emulators": [...], "binaries": [...], "via_libretro": bool}}

import glob
import os
import xml.etree.ElementTree as ET
from functools import lru_cache
from pathlib import Path

# Per-emulator manual overrides: when the emulator name does NOT match the
# binary name installed on target. Keep small — only entries with proven
# divergence. `pgrep -f` widens the net, so loose matches generally fine.
_BIN_OVERRIDES = {
    "libretro": ["retroarch"],
    "dolphin": ["dolphin-emu", "dolphin-emu-nogui"],
    "pcsx2": ["pcsx2-qt", "pcsx2"],
    "rpcs3": ["rpcs3"],
    "duckstation": ["duckstation-qt", "duckstation-nogui"],
    "ppsspp": ["PPSSPPSDL", "ppsspp"],
    "scummvm": ["scummvm"],
    "dosbox": ["dosbox", "dosbox-staging", "dosbox-x"],
    "mupen64plus": ["mupen64plus"],
    "amiberry": ["amiberry"],
    "azahar": ["azahar"],
    "cemu": ["Cemu", "cemu"],
    "eka2l1": ["eka2l1"],
    "yuzu": ["yuzu", "yuzu-cmd"],
    "ryujinx": ["Ryujinx", "Ryujinx.Headless.SDL2"],
    "vita3k": ["Vita3K"],
    "xemu": ["xemu"],
    "easyrpg": ["easyrpg-player"],
    "openbor": ["OpenBOR", "openbor"],
}

# Generated by es-system at build time, installed by es-system.mk. A device may
# also carry one regenerated on demand by `es-system regenerate`; that copy wins
# for REG-Station (SystemData::getConfigPath) and regmsgd (library::systems), so
# it has to win here too or the probe tests a different system set than runs.
_USER_SYSTEMS_CFG = "/userdata/system/configs/regstation/rs_systems.cfg"
_SYSTEMS_CFG = "/usr/share/regstation/rs_systems.cfg"


@lru_cache(maxsize=1)
def load() -> dict[str, dict]:
    """Build {system: {emulators, binaries, via_libretro}}. Cached."""
    table: dict[str, dict] = {}

    path = _systems_cfg_path()
    if not path:
        return table
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError):
        return table

    for system in root.iter("system"):
        sys_name = (system.findtext("name") or "").strip()
        if not sys_name:
            continue
        slot = table.setdefault(sys_name, {"emulators": set(),
                                             "binaries": set(),
                                             "via_libretro": False})
        for emulator in system.iter("emulator"):
            emu_name = (emulator.get("name") or "").strip()
            if emu_name:
                slot["emulators"].add(emu_name)

    # Resolve binaries + libretro flag.
    for sys_name, slot in table.items():
        emus = slot["emulators"]
        slot["via_libretro"] = "libretro" in emus
        bins: set[str] = set()
        for emu in emus:
            bins.update(_BIN_OVERRIDES.get(emu, [emu]))
        slot["emulators"] = sorted(emus)
        slot["binaries"] = sorted(bins)

    return table


def binaries_for(system: str) -> list[str]:
    return load().get(system, {}).get("binaries", [])


# Binary names that ALSO match system utilities — exclude from orphan probe
# (they would always be running). They stay in the table for other lookups.
_ORPHAN_PROBE_BLOCKLIST = frozenset({
    "sh", "bash", "dash", "zsh",
    "python", "python3", "perl", "ruby",
    "ports",
})


def all_binaries(*, for_orphan_probe: bool = False) -> list[str]:
    out: set[str] = set()
    for slot in load().values():
        out.update(slot["binaries"])
    if for_orphan_probe:
        out -= _ORPHAN_PROBE_BLOCKLIST
    return sorted(out)


def _systems_cfg_path() -> str | None:
    """On target, the regenerated file if present, else the installed one. In a
    dev checkout there is neither — rs_systems.cfg is generated — so fall back to
    the newest one left in a build tree, and return None (empty table) when there
    is nothing at all."""
    for candidate in (_USER_SYSTEMS_CFG, _SYSTEMS_CFG):
        if Path(candidate).exists():
            return candidate
    root = _tree_root()
    if root:
        built = glob.glob(str(root / "output/*/build/es-system-*/rs_systems.cfg"))
        if built:
            return max(built, key=os.path.getmtime)
    return None


def _tree_root() -> Path | None:
    """Walk up from this file to the BR2 external root (the dir holding both
    Makefile and configs/). None when not running from a checkout."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "Makefile").is_file() and (parent / "configs").is_dir():
            return parent
    return None
